def add_nums(a, b):
    """Return sum"""
    return a + b

def divide(a, b):
    """Return divide"""
    return a / b
def sub(a, b):
    """Return suubstraction"""
    return a - b

def power(a, b):
    """Return power"""
    return a ** b

def multy(a, b):
    """Return multiplication"""
    return a * b
